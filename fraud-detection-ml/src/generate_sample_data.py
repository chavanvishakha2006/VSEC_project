"""
Sample Data Generator Module (For Code Testing / CI Validation ONLY)

IMPORTANT NOTICE:
Synthetic data generated by this module is strictly intended for code validation, 
unit testing, and Docker/CI pipeline checks when the real Kaggle 'creditcard.csv' 
dataset is unavailable. Synthetic dataset evaluation metrics MUST NOT be presented 
as actual machine learning model performance.
"""

import os
import numpy as np
import pandas as pd


def generate_synthetic_creditcard_data(
    n_samples: int = 5000,
    fraud_ratio: float = 0.01,
    random_state: int = 42
) -> pd.DataFrame:
    """
    Generate synthetic transactions matching the Kaggle Credit Card dataset schema.
    
    Expected Columns:
        - Time: Seconds elapsed since first transaction
        - V1 through V28: Principal components derived via PCA
        - Amount: Transaction amount in currency units
        - Class: 0 for Legitimate, 1 for Fraud
    """
    np.random.seed(random_state)
    n_fraud = max(1, int(n_samples * fraud_ratio))
    n_legit = n_samples - n_fraud

    # Generate Time feature (0 to 172800 seconds - 2 days)
    time_legit = np.sort(np.random.uniform(0, 172800, n_legit))
    time_fraud = np.sort(np.random.uniform(0, 172800, n_fraud))
    time_col = np.concatenate([time_legit, time_fraud])

    # Generate V1 to V28 (Legit centered near 0, Fraud shifted slightly on key components)
    v_features = {}
    for i in range(1, 29):
        feat_name = f"V{i}"
        if i in [1, 3, 4, 10, 12, 14, 17]:
            # Feature shift often seen in fraud PCA components
            legit_vals = np.random.normal(0, 1.0, n_legit)
            fraud_vals = np.random.normal(-2.5, 1.8, n_fraud)
        else:
            legit_vals = np.random.normal(0, 1.0, n_legit)
            fraud_vals = np.random.normal(0, 1.2, n_fraud)
        v_features[feat_name] = np.concatenate([legit_vals, fraud_vals])

    # Generate Amount (Legit: mean ~88, Fraud: small test amounts or high value)
    amount_legit = np.random.exponential(scale=88.0, size=n_legit)
    amount_fraud = np.random.exponential(scale=120.0, size=n_fraud)
    amount_col = np.concatenate([amount_legit, amount_fraud])

    # Class target (0 = Legitimate, 1 = Fraud)
    class_col = np.concatenate([np.zeros(n_legit, dtype=int), np.ones(n_fraud, dtype=int)])

    data = {"Time": time_col}
    data.update(v_features)
    data["Amount"] = amount_col
    data["Class"] = class_col

    df = pd.DataFrame(data)
    # Shuffle dataframe
    df = df.sample(frac=1.0, random_state=random_state).reset_index(drop=True)
    return df


def save_synthetic_dataset(output_path: str = "data/sample_creditcard.csv", n_samples: int = 5000):
    """
    Generate and save synthetic credit card dataset for offline validation.
    """
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    df = generate_synthetic_creditcard_data(n_samples=n_samples)
    df.to_csv(output_path, index=False)
    print(f"[NOTICE] Synthetic dataset generated successfully ({len(df)} samples) at '{output_path}'.")
    print("WARNING: This dataset is strictly for code validation/testing. Do NOT report metrics as true performance.")
    return output_path


if __name__ == "__main__":
    save_synthetic_dataset()
